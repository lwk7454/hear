#!/usr/bin/env python3
import subprocess
import json
import os
import sys

# --- Configuration ---
REGION = "ca-central-1"
ENV = "dev"
PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SSM_PREFIX = f"/hear/{ENV}/"

SERVER_ENV_PATH = os.path.join(PROJECT_ROOT, "apps/server/.env")
WEB_ENV_PATH = os.path.join(PROJECT_ROOT, "apps/web/.env")

def fetch_all_params_by_path(prefix):
    """Recursively fetches all parameters under a path using AWS CLI."""
    params = {}
    next_token = None
    
    print(f"🔍 Scanning SSM by path: {prefix}...")
    
    while True:
        cmd = [
            "aws", "ssm", "get-parameters-by-path",
            "--path", prefix,
            "--recursive",
            "--with-decryption",
            "--region", REGION,
            "--output", "json"
        ]
        
        if next_token:
            cmd.extend(["--next-token", next_token])
            
        try:
            result = subprocess.run(cmd, capture_output=True, text=True, check=True)
            data = json.loads(result.stdout)
            
            for p in data.get("Parameters", []):
                # /hear/dev/VAR_NAME -> VAR_NAME
                key = p["Name"].split("/")[-1]
                params[key] = p["Value"]
                
            next_token = data.get("NextToken")
            if not next_token:
                break
                
        except subprocess.CalledProcessError as e:
            print(f"❌ Error fetching SSM params: {e.stderr}")
            sys.exit(1)
        except FileNotFoundError:
            print("❌ Error: 'aws' CLI not found. Please install AWS CLI.")
            sys.exit(1)
            
    return params

def write_env_file(path, params, is_web=False):
    """Writes the .env file with filtered parameters."""
    print(f"📝 Writing {path}...")
    
    # Filter for Web (Only NEXT_PUBLIC_)
    if is_web:
        filtered_params = {k: v for k, v in params.items() if k.startswith("NEXT_PUBLIC_")}
    else:
        # Server gets everything
        filtered_params = params.copy()

    with open(path, "w") as f:
        f.write(f"# Auto-generated by scripts/setup-local-env.py from AWS SSM ({REGION})\n")
        f.write(f"# Scanned Prefix: {SSM_PREFIX}\n\n")
        
        # Inject Local Defaults (if missing from SSM or just always useful as overrides)
        if not is_web:
             # Server Defaults
             if "PORT" not in filtered_params:
                 f.write("PORT=8000\n")
             if "CORS_ORIGINS" not in filtered_params:
                 f.write("CORS_ORIGINS=http://localhost:3000,http://127.0.0.1:3000\n")
             if "WORKER_URL" not in filtered_params:
                 f.write("WORKER_URL=http://127.0.0.1:8001\n") 
             if "HIGGS_API_URL" not in filtered_params:
                 f.write("HIGGS_API_URL=http://127.0.0.1:8002\n")
             f.write("\n")

        if is_web:
             # Web Defaults
             if "NEXT_PUBLIC_API_URL" not in filtered_params:
                 f.write("NEXT_PUBLIC_API_URL=http://localhost:8000\n")
             f.write("\n")

        # Write params
        for key, val in sorted(filtered_params.items()):
            if " " in val or "#" in val:
                val = f'"{val}"'
            f.write(f"{key}={val}\n")

    print(f"✅ Wrote {len(filtered_params)} variables to {path}")

def main():
    print(f"🚀 Setting up local environment from AWS SSM ({REGION})...")
    
    # 1. Fetch all
    all_params = fetch_all_params_by_path(SSM_PREFIX)
    print(f"⬇️  Found {len(all_params)} parameters.")

    # 2. Write Server .env (All params)
    write_env_file(SERVER_ENV_PATH, all_params, is_web=False)

    # 3. Write Web .env (Only NEXT_PUBLIC_*)
    write_env_file(WEB_ENV_PATH, all_params, is_web=True)

    print("\n✨ Done! You can now run 'npm run dev'.")

if __name__ == "__main__":
    main()
